import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { spawnSync } from "node:child_process";
const HERE = dirname(fileURLToPath(import.meta.url));
const FIX = mkdtempSync(join(tmpdir(), "rss-fixtures-"));
const gen = spawnSync(process.env.PYTHON || (process.platform === "win32" ? "python" : "python3"), [join(HERE, "test", "make_fixtures.py")], { env: { ...process.env, FIXTURE_ROOT: FIX }, encoding: "utf8" });
if (gen.status !== 0) { console.error("fixture generation failed", gen.stderr); process.exit(2); }
const t = new StdioClientTransport({ command: "node", args: [join(HERE, "server.mjs")] });
const c = new Client({ name: "test", version: "0" });
await c.connect(t);
let pass = 0, fail = 0;
const check = (name, ok, extra = "") => { (ok ? pass++ : fail++); console.log(ok ? "PASS" : "FAIL", name, extra); };
const tools = (await c.listTools()).tools.map((x) => x.name).sort();
check("lists 2 tools", tools.join() === "scan_repo,triage_summary", tools.join());
const vuln = await c.callTool({ name: "scan_repo", arguments: { path: join(FIX, "vulnerable-app") } });
const v = vuln.structuredContent;
check("vulnerable app has HIGH findings", v.counts.HIGH >= 5, JSON.stringify(v.counts));
check("secrets redacted", !JSON.stringify(v).match(/sk_live_[0-9a-zA-Z]{20}/));
const clean = await c.callTool({ name: "scan_repo", arguments: { path: join(FIX, "clean-app") } });
check("clean app has 0 HIGH", clean.structuredContent.counts.HIGH === 0, JSON.stringify(clean.structuredContent.counts));
const bad = await c.callTool({ name: "scan_repo", arguments: { path: join(FIX, "nope") } });
check("bad path returns isError", bad.isError === true, bad.content[0].text.slice(0, 60));
const tri = await c.callTool({ name: "triage_summary", arguments: { path: join(FIX, "vulnerable-app") } });
check("triage says do not deploy", /Do not deploy/.test(tri.content[0].text));
const lim = await c.callTool({ name: "scan_repo", arguments: { path: join(FIX, "vulnerable-app"), limit: 3, min_severity: "HIGH" } });
check("limit and min_severity respected", lim.structuredContent.shown === 3 && lim.structuredContent.findings.every((f) => f.severity === "HIGH"));
console.log(`\n${pass} passed, ${fail} failed`);
await c.close();
rmSync(FIX, { recursive: true, force: true });
process.exit(fail ? 1 : 0);
